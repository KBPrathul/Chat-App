import User from "../models/user.model.js";
import bcrypt from "bcryptjs";
import generateTokenAndSetCookie from "../utils/generateToken.js";

export const signup = async (req,res) => {
    try{
        // We are getting the inputs from the user as we have to setup our database and create our model to take and save the needed info
        const {fullName,username,password,confirmPassword,gender} = req.body;

        if(password !== confirmPassword){
            return res.status(400).json({error:"Passwords dont match"});
        }

        // Helps in checking if the username already exists in the database, so that we can avoid duplicate usernames and maintain uniqueness.
        const user = await User.findOne({username});

        if(user){
            return res.status(400).json({error:"Username already exists"});
        }

        // Hash password so that even if someone gets access to the database, they cant see the actual password.
        // Higher the genSalt value, more secure the password is, but it also takes more time to hash the password.
        const salt = await bcrypt.genSalt(10);
        // We are hashing the password using the salt, so that even if two users have the same password, their hashed passwords will be different in the database.
        const hashedPassword = await bcrypt.hash(password, salt);

        const boyProfilePic = `https://api.dicebear.com/9.x/pixel-art/svg?seed=${username}`;
		const girlProfilePic = `https://api.dicebear.com/9.x/pixel-art/svg?seed=${username}`;

        //Instead of fullName:fullName, we can write just fullName, since the key and value are same and similarly for others as well
        const newUser = new User({
			fullName,
			username,
			password: hashedPassword,
			gender,
			profilePic: gender === "male" ? boyProfilePic : girlProfilePic,
		});

        if(newUser){
            generateTokenAndSetCookie(newUser._id, res);

            // Saves the new user to the database
            await newUser.save();

            // _id is automatically generated by MongoDB, so we can directly use it here
            res.status(201).json({
                _id: newUser._id,
                fullName: newUser.fullName,
                username: newUser.username,
                profilePic: newUser.profilePic,
            });
        }
        else{
            res.status(400).json({error:"Invalid user data"});
        }
    }
    catch(error){
        console.log("Error in signup controller", error.message);
        res.status(500).json({error:"Internal Server Error"});
    }
};

export const login = async (req,res) => {
    try{
        const {username, password} = req.body;
        const user = await User.findOne({username});
        // We have to decode the password entered by the user and compare it with the hashed password stored in the database.
        // "" is added to handle the case when user is not found and user.password is undefined, so that it doesnt throw an error while comparing and instead returns false.
        const isPasswordCorrect = await bcrypt.compare(password, user.password || "");

        if(!user || !isPasswordCorrect){
            return res.status(400).json({error:"Invalid username or password"});
        }

        generateTokenAndSetCookie(user._id, res);

        // We are sending the user data in the response, so that we can display it in the frontend and use it for other purposes like showing the profile pic, full name, etc.
        res.status(200).json({
            _id: user._id,
            fullName: user.fullName,
            username: user.username,
            profilePic: user.profilePic,
        });
    }
    catch(error){
        console.log("Error in login controller", error.message);
        res.status(500).json({error:"Internal Server Error"});
    }
};

export const logout = (req,res) => {
    try{
        // Clearing the cookie by setting its value to an empty string and maxAge to 0, so that it gets deleted from the browser.
        res.cookie("jwt", "", {maxAge:0});
        res.status(200).json({message:"Logged out successfully"});
    }
    catch(error){
        console.log("Error in logout controller", error.message);
        res.status(500).json({error:"Internal Server Error"});
    }
};
